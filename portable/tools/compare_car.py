#!/usr/bin/env python3
"""Diff same-frame PGR1 CPU-reference and native-GPU PPM captures.

The images are generated by PGR1_COMPARE_FRAME in the same run. A screenshot from
another frame/session is not comparable. Outputs a P6 red heatmap, no image libs.
"""
import argparse
from pathlib import Path


def ppm(path):
    with path.open('rb') as f:
        if f.readline().strip() != b'P6': raise ValueError(f'{path}: requires P6 PPM')
        size = f.readline().split()
        if len(size) != 2: raise ValueError(f'{path}: bad dimensions')
        w, h = map(int, size)
        if not 0 < w <= 16384 or not 0 < h <= 16384: raise ValueError(f'{path}: unreasonable dimensions')
        if f.readline().strip() != b'255': raise ValueError(f'{path}: max must be 255')
        data = f.read()
        if len(data) != w*h*3: raise ValueError(f'{path}: expected {w*h*3} pixel bytes, got {len(data)}')
        return w, h, data


def compare(path_a, path_b, region, heatmap, threshold):
    w, h, ref = ppm(path_a)
    wg, hg, gpu = ppm(path_b)
    if (w, h) != (wg, hg): raise ValueError(f'different image dimensions: {(w, h)} vs {(wg, hg)}')
    if region is None: x0, y0, cw, ch = 0, 0, w, h
    else: x0, y0, cw, ch = region
    if x0 < 0 or y0 < 0 or cw <= 0 or ch <= 0 or x0+cw > w or y0+ch > h:
        raise ValueError(f'invalid region {(x0, y0, cw, ch)} for image {w}x{h}')
    rgb_sum = 0; bad = 0; maximum = 0
    result = bytearray(w*h*3)
    for y in range(h):
        for x in range(w):
            i = (y*w+x)*3
            diffs = [abs(ref[i+k]-gpu[i+k]) for k in range(3)]
            strength = max(diffs)
            result[i:i+3] = bytes((strength, 0, 0))
            if not (x0 <= x < x0+cw and y0 <= y < y0+ch): continue
            rgb_sum += sum(diffs); bad += strength > threshold; maximum = max(maximum,strength)
    n = cw*ch
    print(f'Inputs: {w}x{h}, region=({x0},{y0},{cw},{ch}), threshold={threshold}/255')
    print(f'Mean RGB absolute error: {rgb_sum/(3*n):.5f}/255')
    print(f'Max channel error: {maximum}/255')
    print(f'Pixels with any channel error > threshold: {bad}/{n} ({bad/n:.2%})')
    if heatmap:
        with heatmap.open('wb') as f:
            f.write(f'P6\n{w} {h}\n255\n'.encode()); f.write(result)
        print(f'Heatmap (red = difference): {heatmap}')


def main():
    p=argparse.ArgumentParser(description='Compare matched-frame CPU and GPU PGR1 PPM captures')
    p.add_argument('directory', type=Path, nargs='?', default=Path('.local/run/linux'))
    p.add_argument('--region', type=int, nargs=4, metavar=('X','Y','WIDTH','HEIGHT'))
    p.add_argument('--threshold', type=int, default=4)
    p.add_argument('--heatmap', type=Path)
    args=p.parse_args()
    if not 0 <= args.threshold <= 255: p.error('threshold must be 0..255')
    try:
        compare(args.directory/'compare-reference.ppm', args.directory/'compare-gpu.ppm',
                args.region, args.heatmap, args.threshold)
    except (OSError, ValueError) as e: p.error(str(e))

if __name__=='__main__': main()
